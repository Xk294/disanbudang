// Helper functions for easy querying
export function getVirtualTourByHeritageId(heritageId: string): VirtualHeritageTour | undefined {
  return Object.values(VIRTUAL_TOURS).find(
    tour => tour.heritageId === heritageId || tour.heritageSlug === heritageId,
  )
}

export function getAllVirtualTours(): VirtualHeritageTour[] {
  return Object.values(VIRTUAL_TOURS)
}
